"""Evaluate trialmatch.

1. Matching: 5 synthetic patients x 6 synthetic trials (data/), with a gold verdict per pair
   (eval/match_gold.json). Errors are split into UNSAFE (tool says likely_eligible or
   needs_review when the patient is ineligible, or likely_eligible when data is missing)
   and CONSERVATIVE (tool asks for review or excludes when it should not).
2. Criterion parsing: 24 development criteria (eval/criteria_gold.json, used while writing the
   regex parser) and 16 held-out criteria (eval/criteria_heldout.json, never tuned on).

  python eval/run_eval.py [--llm] [--check]
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT.parent / "src"))

from trialmatch.criteria import parse_llm, parse_rules  # noqa: E402
from trialmatch.matcher import match  # noqa: E402
from trialmatch.models import Criterion  # noqa: E402
from trialmatch.pipeline import load_patient, load_trials  # noqa: E402

RANK = {"likely_eligible": 0, "needs_review": 1, "ineligible": 2}


def eval_matching(client=None):
    gold = json.loads((ROOT / "match_gold.json").read_text())
    trials = {t.nct_id: t for t in load_trials(str(ROOT.parent / "data/trials/synthetic_trials.json"))}
    ok = unsafe = conservative = 0
    errors = []
    for pid, row in sorted(gold.items()):
        patient = load_patient(str(ROOT.parent / f"data/patients/{pid}.json"))
        for nct, want in sorted(row.items()):
            got = match(patient, trials[nct], client).verdict
            if got == want:
                ok += 1
                continue
            kind = "UNSAFE" if RANK[got] < RANK[want] else "conservative"
            unsafe += kind == "UNSAFE"
            conservative += kind == "conservative"
            errors.append(f"{pid} x {nct}: expected {want}, got {got} ({kind})")
    n = sum(len(r) for r in gold.values())
    return {"accuracy": ok / n, "unsafe": unsafe, "conservative": conservative, "n": n, "errors": errors}


def eval_parsing(client=None, name="criteria_gold.json"):
    gold = json.loads((ROOT / name).read_text())
    crits = [Criterion(text=g["text"], kind=g["kind"]) for g in gold]
    parsed = parse_llm(crits, client) if client else [parse_rules(c) for c in crits]
    ok, errors = 0, []
    for g, p in zip(gold, parsed):
        want = (g["type"], g.get("lab"), g.get("low"), g.get("high"))
        got = (p.type if p.type != "condition" else "condition", p.lab, p.low, p.high)
        if g["type"] == "condition":
            got, want = got[:1], want[:1]
        if got == want:
            ok += 1
        else:
            errors.append(f"'{g['text']}': expected {want}, got {got}")
    return {"accuracy": ok / len(gold), "n": len(gold), "errors": errors}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--llm", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    res = {"rules": (eval_matching(), eval_parsing(), eval_parsing(None, "criteria_heldout.json"))}
    if args.llm:
        from trialmatch.llm import client_from_env
        c = client_from_env()
        res["llm"] = (eval_matching(c), eval_parsing(c), eval_parsing(c, "criteria_heldout.json"))
    m0, p0, h0 = res["rules"]
    out = ["# Evaluation results", "", "Generated by `python eval/run_eval.py`. All patients and trials are synthetic.",
           "", f"## Matching ({m0['n']} patient-trial pairs) and criterion parsing", "",
           f"Parse accuracy is reported on the development set ({p0['n']} criteria, used while writing the regex "
           f"parser) and on a held-out set ({h0['n']} criteria, written afterwards and never tuned on).", "",
           "| Criteria parser | Verdict accuracy | Unsafe errors | Conservative errors | Parse acc. (dev) "
           "| Parse acc. (held-out) |", "|---|---|---|---|---|---|"]
    for name, (m, p, h) in res.items():
        out.append(f"| {name} | {m['accuracy']:.2f} | {m['unsafe']} | {m['conservative']} | {p['accuracy']:.2f} "
                   f"| {h['accuracy']:.2f} |")
    if "llm" not in res:
        out.append("| llm | not run here: requires credentials. Run `python eval/run_eval.py --llm` | | | | |")
    for name, (m, p, h) in res.items():
        out += ["", f"### {name}: matching errors", ""] + ([f"- {e}" for e in m["errors"]] or ["- none"])
        out += ["", f"### {name}: parsing errors (dev)", ""] + ([f"- {e}" for e in p["errors"]] or ["- none"])
        out += ["", f"### {name}: parsing errors (held-out)", ""] + ([f"- {e}" for e in h["errors"]] or ["- none"])
    (ROOT / "RESULTS.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))
    if args.check:
        base = json.loads((ROOT / "baseline.json").read_text())
        if m0["unsafe"] > base["max_unsafe"] or m0["accuracy"] < base["rules_match_accuracy"] \
                or p0["accuracy"] < base["rules_parse_accuracy"]:
            print("REGRESSION", file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
